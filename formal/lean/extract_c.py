#!/usr/bin/env python3
"""Cut the two runtime-free functions out of Lean's C output for FlWqCode.lean.

Lean's generated module also holds boxed wrappers and an initializer that need Lean's runtime; only the
`uint8_t` functions named in WANT are kept. Usage: extract_c.py <FlWqCode.c> <out.inc>"""
import hashlib
import pathlib
import re
import sys

WANT = ("fl_wq_transition_allowed", "fl_wq_state_terminal")


def function_source(text: str, name: str) -> str:
    m = re.search(r"^LEAN_EXPORT uint8_t %s\(([^)]*)\)\{\n" % re.escape(name), text, re.M)
    if not m:
        sys.exit("extract_c: %s not found as a definition" % name)
    depth, i = 0, m.start()
    while True:
        c = text[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
        if depth == 0 and c == "}":
            break
    body = text[m.start():i]
    if "lean_object" in body or "lean_inc" in body or "lean_dec" in body or "lean_box" in body:
        sys.exit("extract_c: %s uses Lean runtime objects; keep exported functions on UInt8" % name)
    body = body.replace("LEAN_EXPORT uint8_t", "static uint8_t", 1)
    return "\n".join(l for l in body.split("\n") if l.strip() != "_start:") + "\n"


def main() -> None:
    src = pathlib.Path(sys.argv[1]).read_text()
    lean_src = pathlib.Path(__file__).with_name("FlWqCode.lean").read_bytes()
    digest = hashlib.sha256(lean_src).hexdigest()
    out = [
        "/* GENERATED by formal/lean/build.sh from formal/lean/FlWqCode.lean (Lean 4 `lean -c`). Do not edit.\n",
        " * formal/lean/FlWq.lean proves these agree with the workqueue state machine model. Only the two\n",
        " * runtime-free functions are kept; Lean's boxed wrappers and initializer are not part of the kernel.\n",
        " * source-sha256: %s */\n" % digest,
        "static inline uint8_t lean_uint8_dec_eq(uint8_t a, uint8_t b) { return a == b; }\n\n",
    ]
    out += [function_source(src, n) + "\n" for n in WANT]
    pathlib.Path(sys.argv[2]).write_text("".join(out))


main()
